/*Realizar un programa que imprima en pantalla los numeros del 1 al 100. */

public class contador{ // Inicio del programa
    public static void main(String[] args){ // Inicio del metodo
       
        for (int i=1; i<=100;){ // Para que el ciclo se cierre el contador i tiene que llegar a 100
            System.out.print(i); // Salida
            i++; // Suma del contador i = i+1
        } // Cierre del ciclo
    } // Cierre del metodo
} // Fin del programa