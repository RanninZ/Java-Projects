/*Realizar un programa que imprima en pantalla los numeros del 1 al 100
Sin conocer las estructuras repetitivas podemos resolver el problema empleado una estructura secuencial.
Inicializamos una variable con el valor 1, luego imprimimo la variable, incrementamos nuevamente la variable
y así sucesivamente. */



public class numeros_uno_cien {
    public static void main(String[] args){
        int a = 1;
       
        while (a <= 100){
            System.out.print(a);
            a++;
        }
        
        

    }
}
